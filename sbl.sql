-- Creating the database
CREATE DATABASE IF NOT EXISTS sbl_bank;
USE sbl_bank;

-- Creating table for provinces
CREATE TABLE provinces (
    id INT PRIMARY KEY,
    title VARCHAR(100) NOT NULL
);

-- Creating table for districts
CREATE TABLE districts (
    id INT PRIMARY KEY,
    dist_title VARCHAR(100) NOT NULL,
    province_id INT,
    FOREIGN KEY (province_id) REFERENCES provinces(id)
);

-- Creating table for branches
CREATE TABLE branches (
    id INT PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    title_np VARCHAR(100),
    type VARCHAR(50) NOT NULL,
    code VARCHAR(50),
    code_id VARCHAR(50),
    detail TEXT,
    detail_np TEXT,
    manager_name VARCHAR(100),
    manager_name_np VARCHAR(100),
    address TEXT,
    address_np TEXT,
    phone VARCHAR(100),
    email VARCHAR(100),
    email_detail VARCHAR(100),
    region VARCHAR(100),
    is_regional_office VARCHAR(10),
    latitude DECIMAL(10,8),
    longitude DECIMAL(11,8),
    status VARCHAR(20),
    category VARCHAR(50),
    fax VARCHAR(50),
    district_id INT,
    province_id INT,
    `order` INT,
    created_on BIGINT,
    created_by VARCHAR(50),
    updated_on BIGINT,
    updated_by VARCHAR(50),
    hide_in_website VARCHAR(10),
    bm_phone VARCHAR(100),
    is_upcoming_branch VARCHAR(10),
    FOREIGN KEY (district_id) REFERENCES districts(id),
    FOREIGN KEY (province_id) REFERENCES provinces(id)
);

